/** Actual HTTP and Ed25519; workflow facts/authority are explicit contract data. */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import test from 'node:test';
import { fixture } from './member-local-execution-protocol-fixture.mjs';

const defaults = {
  model: { provider: 'contract', model: 'contract-model', maxTokens: 1000 },
  workspace: { kind: 'text-only' },
  capabilities: { resultIntent: 'zhuma-native-result-intent@1', localTools: [] },
};
const targetOf = (h) => {
  const { nodeId, ...target } = h.input.target;
  return target;
};
function views() {
  let intent;
  return (request) => {
    const { payload, deviceId, requestId } = request;
    if (!intent)
      intent = {
        schemaVersion: 1,
        intentId: randomUUID(),
        actorId: 'chen',
        spaceId: payload.target.spaceId,
        deviceId,
        keyEpoch: 1,
        generation: 1,
        version: 1,
        status: 'running',
        defaults: payload.defaults,
        budget: payload.budget,
        nodeIds: ['produce'],
        commandReceipts: [{ requestId, kind: 'start', fingerprint: 'a'.repeat(64), generation: 1 }],
      };
    if (request.operation === 'workflow-resume')
      intent = { ...intent, generation: intent.generation + 1, version: intent.version + 1 };
    if (request.operation === 'workflow-stop') intent = { ...intent, status: 'stopping' };
    return {
      disposition: 'unchanged',
      scope: {
        ...payload.target,
        actorId: intent.actorId,
        deviceId,
        intentId: intent.intentId,
        generation: intent.generation,
      },
      intent,
      state: request.operation === 'workflow-stop' ? 'stopping' : 'waiting',
      requiresResume: false,
      serverTime: Date.now(),
      expiresAt: Date.now() + 60000,
      activeWork: [],
      activeReviews: [],
      candidates: [],
      attention: [],
    };
  };
}
test('workflow protocol: legacy open stays inert and unadvertised workflow commands fail closed', async (t) => {
  const h = await fixture(t),
    p = await h.open();
  t.after(() => p.close());
  assert.equal(p.supportsAutomaticWorkflow, false);
  assert.deepEqual(h.seen.find((v) => v.request.operation === 'info').request.payload, {});
  assert.equal(await p.negotiateWorkflow(), false);
  await assert.rejects(p.workflowStart(randomUUID(), { target: targetOf(h), defaults }), {
    code: 'remote-protocol-unsupported',
  });
  assert.equal(
    h.seen.some((v) => v.request.operation === 'workflow-start'),
    false,
  );
  assert.equal(h.acceptCalls(), 0);
});
test('workflow protocol: negotiate and sign normalized five-operation payloads on the existing device; no Run is accepted', async (t) => {
  const h = await fixture(t, { workflow: views() }),
    p = await h.open();
  t.after(() => p.close());
  assert.equal(p.supportsAutomaticWorkflow, false);
  const target = targetOf(h),
    requestId = randomUUID();
  const started = await p.workflowStart(requestId, { target, defaults });
  assert.equal(p.supportsAutomaticWorkflow, true);
  const sent = h.seen.find((v) => v.request.operation === 'workflow-start').request;
  assert.deepEqual(sent.payload.budget, { concurrent: 1, automaticRevisions: 2 });
  assert.equal(sent.requestId, requestId);
  assert.equal(h.seen.filter((v) => v.request.operation === 'register-device').length, 1);
  assert(
    h.seen.some(
      (v) =>
        v.request.operation === 'info' && v.request.payload.workflow === 'zhuma-remote-workflow@1',
    ),
  );
  const workflow = { intentId: started.intent.intentId, generation: started.intent.generation };
  await p.workflowStatus({ target });
  await p.workflowNext({ target, workflow });
  const resumed = await p.workflowResume(randomUUID(), {
    target,
    workflow,
    expectedVersion: started.intent.version,
  });
  const stopped = await p.workflowStop(randomUUID(), {
    target,
    workflow: { intentId: workflow.intentId, generation: resumed.intent.generation },
  });
  assert.equal(stopped.state, 'stopping');
  assert.equal(h.acceptCalls(), 0);
  assert.equal(
    [...h.rows.values()].filter((v) => v.drive).length,
    0,
    'No private Run permit is generated by workflow data',
  );
});
test('workflow protocol: a valid response for a different actor cannot become a local arm', async (t) => {
  const normal = views();
  const h = await fixture(t, {
      workflow: (request) => {
        const v = normal(request);
        return {
          ...v,
          scope: { ...v.scope, actorId: 'outside' },
          intent: { ...v.intent, actorId: 'outside' },
        };
      },
    }),
    p = await h.open();
  t.after(() => p.close());
  await assert.rejects(p.workflowStart(randomUUID(), { target: targetOf(h), defaults }), {
    code: 'local-mismatch',
  });
  assert.equal(h.acceptCalls(), 0);
});
